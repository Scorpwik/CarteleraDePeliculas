create table public.sesiones (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  nombre text not null,
  tiempo_disponible_min integer not null,
  creada_en timestamptz not null default now(),
  constraint sesiones_nombre_len check (char_length(btrim(nombre)) between 1 and 80),
  constraint sesiones_tiempo_rango check (tiempo_disponible_min between 30 and 600)
);

create table public.sesion_peliculas (
  id bigint generated by default as identity primary key,
  sesion_id bigint not null references public.sesiones (id) on delete cascade,
  tmdb_id integer not null,
  titulo text not null,
  poster_url text,
  duracion_min integer not null check (duracion_min > 0),
  orden integer not null check (orden >= 0),
  unique (sesion_id, tmdb_id),
  unique (sesion_id, orden)
);

alter table public.sesiones enable row level security;
alter table public.sesion_peliculas enable row level security;

create policy "sesiones_select_own"
  on public.sesiones for select to authenticated
  using (auth.uid() = user_id);

create policy "sesiones_insert_own"
  on public.sesiones for insert to authenticated
  with check (auth.uid() = user_id);

create policy "sesiones_delete_own"
  on public.sesiones for delete to authenticated
  using (auth.uid() = user_id);

create policy "sesion_peliculas_select_own"
  on public.sesion_peliculas for select to authenticated
  using (
    exists (
      select 1 from public.sesiones s
      where s.id = sesion_id and s.user_id = auth.uid()
    )
  );

create policy "sesion_peliculas_insert_own"
  on public.sesion_peliculas for insert to authenticated
  with check (
    exists (
      select 1 from public.sesiones s
      where s.id = sesion_id and s.user_id = auth.uid()
    )
  );

create policy "sesion_peliculas_delete_own"
  on public.sesion_peliculas for delete to authenticated
  using (
    exists (
      select 1 from public.sesiones s
      where s.id = sesion_id and s.user_id = auth.uid()
    )
  );
